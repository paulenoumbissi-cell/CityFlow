/**
 * Recherche instantanée et tolérante aux fautes d'accents
 */
export function searchLandmarks(query, city = "Yaoundé") {
  const normCity = city && city.toLowerCase().includes("douala") ? "Douala" : "Yaoundé";
  const list = CITY_LANDMARKS[normCity] || [];
  if (!query || !query.trim()) return list;

  const normalize = (str) =>
    str.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").trim();

  const q = normalize(query);
  return list.filter((item) => {
    const nName = normalize(item.name);
    const nDist = normalize(item.district || "");
    const nDesc = normalize(item.desc || "");
    return nName.includes(q) || nDist.includes(q) || nDesc.includes(q);
  });
}


